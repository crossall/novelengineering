// 편의 함수 (원본을 바꾸지 않고 새 배열을 돌려준다)
window.STORY.byId = function (id) { return this.sentences.find(s => s.id === id); };
window.STORY.sceneName = function (sceneId) { const s = this.scenes.find(x => x.id === sceneId); return s ? s.name : sceneId; };
window.STORY.search = function (query) {
  const q = (query || "").trim();
  if (!q) return [];
  const tokens = q.replace(/[?!.,]/g, " ").split(/\s+/).filter(t => t.length >= 1);
  return this.sentences
    .map(s => {
      let score = 0;
      for (const t of tokens) {
        if (s.text.includes(t)) score += 2;
        if (s.tags.some(tag => tag.includes(t) || t.includes(tag))) score += 3;
      }
      return { s, score };
    })
    .filter(r => r.score > 0)
    .sort((a, b) => b.score - a.score)
    .map(r => r.s);
};
